-- key: ID
SELECT d."ID" AS "ID",
       d."Name_lang" AS "Name_lang",
       d."ItemID1" AS "ItemID1",
       d."ItemID2" AS "ItemID2",
       d."ItemID3" AS "ItemID3",
       d."ItemID4" AS "ItemID4",
       d."ItemID5" AS "ItemID5",
       d."ItemID6" AS "ItemID6",
       d."ItemID7" AS "ItemID7",
       d."ItemID8" AS "ItemID8",
       d."ItemID9" AS "ItemID9",
       d."ItemID10" AS "ItemID10",
       d."ItemID11" AS "ItemID11",
       d."ItemID12" AS "ItemID12",
       d."ItemID13" AS "ItemID13",
       d."ItemID14" AS "ItemID14",
       d."ItemID15" AS "ItemID15",
       d."ItemID16" AS "ItemID16",
       d."ItemID17" AS "ItemID17",
       COALESCE(MAX(CASE WHEN s."Slot" = 1 THEN s."SpellID" END), 0) AS "SetSpellID1",
       COALESCE(MAX(CASE WHEN s."Slot" = 2 THEN s."SpellID" END), 0) AS "SetSpellID2",
       COALESCE(MAX(CASE WHEN s."Slot" = 3 THEN s."SpellID" END), 0) AS "SetSpellID3",
       COALESCE(MAX(CASE WHEN s."Slot" = 4 THEN s."SpellID" END), 0) AS "SetSpellID4",
       COALESCE(MAX(CASE WHEN s."Slot" = 5 THEN s."SpellID" END), 0) AS "SetSpellID5",
       COALESCE(MAX(CASE WHEN s."Slot" = 6 THEN s."SpellID" END), 0) AS "SetSpellID6",
       COALESCE(MAX(CASE WHEN s."Slot" = 7 THEN s."SpellID" END), 0) AS "SetSpellID7",
       COALESCE(MAX(CASE WHEN s."Slot" = 8 THEN s."SpellID" END), 0) AS "SetSpellID8",
       COALESCE(MAX(CASE WHEN s."Slot" = 1 THEN s."Threshold" END), 0) AS "SetThreshold1",
       COALESCE(MAX(CASE WHEN s."Slot" = 2 THEN s."Threshold" END), 0) AS "SetThreshold2",
       COALESCE(MAX(CASE WHEN s."Slot" = 3 THEN s."Threshold" END), 0) AS "SetThreshold3",
       COALESCE(MAX(CASE WHEN s."Slot" = 4 THEN s."Threshold" END), 0) AS "SetThreshold4",
       COALESCE(MAX(CASE WHEN s."Slot" = 5 THEN s."Threshold" END), 0) AS "SetThreshold5",
       COALESCE(MAX(CASE WHEN s."Slot" = 6 THEN s."Threshold" END), 0) AS "SetThreshold6",
       COALESCE(MAX(CASE WHEN s."Slot" = 7 THEN s."Threshold" END), 0) AS "SetThreshold7",
       COALESCE(MAX(CASE WHEN s."Slot" = 8 THEN s."Threshold" END), 0) AS "SetThreshold8",
       d."RequiredSkill" AS "RequiredSkill",
       d."RequiredSkillRank" AS "RequiredSkillRank"
FROM "dbc_itemset" d
LEFT JOIN (SELECT "ItemSetID", "SpellID", "Threshold",
                  ROW_NUMBER() OVER (PARTITION BY "ItemSetID" ORDER BY "ID") AS "Slot"
           FROM "dbc_itemsetspell") s ON s."ItemSetID" = d."ID"
GROUP BY d."ID"
