inline uint32 ToClassicCastResult(uint32 result)
{
    if (result == 0xFF) // SPELL_CAST_OK
        return 0;
    if (result < sizeof(CLASSIC_CAST_RESULTS) / sizeof(CLASSIC_CAST_RESULTS[0]))
        return CLASSIC_CAST_RESULTS[result];
    return CLASSIC_CAST_FAILED_UNKNOWN;
}

