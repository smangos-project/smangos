#include "DbcGenerator.h"

#include <algorithm>
#include <cctype>
#include <sstream>
#include <unordered_set>

namespace
{
    std::string ToLower(std::string const& text)
    {
        std::string result = text;
        std::transform(result.begin(), result.end(), result.begin(),
                       [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
        return result;
    }

    std::string EscapeCString(std::string const& text)
    {
        std::string out;
        out.reserve(text.size());
        for (char c : text)
        {
            if (c == '"' || c == '\\')
                out += '\\';
            out += c;
        }
        return out;
    }

    char const* FieldTypeEnumName(std::string const& type)
    {
        if (type == "int")
            return "DbcFieldType::Int";
        if (type == "float")
            return "DbcFieldType::Float";
        if (type == "string")
            return "DbcFieldType::String";
        return "DbcFieldType::LocString";
    }

    // The SQL column name(s) DbcSchema would give this field: the field name itself for a
    // scalar, or "Name1".."NameN" for an array.
    std::vector<std::string> FlattenedColumnNames(DbdResolvedField const& field)
    {
        if (field.arrayLength <= 1)
            return { field.name };

        std::vector<std::string> names;
        for (int i = 1; i <= field.arrayLength; ++i)
            names.push_back(field.name + std::to_string(i));
        return names;
    }

    void EmitFieldInitializer(std::ostringstream& out, DbdResolvedField const& field)
    {
        out << "    { \"" << EscapeCString(field.name) << "\", " << FieldTypeEnumName(field.type) << ", "
            << field.bits << ", " << (field.isUnsigned ? "false" : "true") << ", " << field.arrayLength << ", "
            << (field.isId ? "true" : "false") << ", " << (field.isRelation ? "true" : "false") << ", "
            << (field.isNonInline ? "true" : "false") << ", "
            << (field.HasForeignKey() ? ("\"" + EscapeCString(field.foreignTable) + "\"") : "nullptr") << ", "
            << (field.HasForeignKey() ? ("\"" + EscapeCString(field.foreignColumn) + "\"") : "nullptr")
            << " },\n";
    }
}

DbcGeneratorResult GenerateDbcTablesSource(std::vector<DbdTable> const& tables, std::string const& wowdbdefsCommit)
{
    std::vector<DbdTable> sorted = tables;
    std::sort(sorted.begin(), sorted.end(),
              [](DbdTable const& a, DbdTable const& b) { return a.name < b.name; });

    DbcGeneratorResult result;
    for (DbdTable const& table : sorted)
    {
        std::unordered_set<std::string> seenColumns;
        for (DbdResolvedField const& field : table.fields)
        {
            if (field.type == "int" && field.bits == 0)
            {
                result.errors.push_back({ table.name, field.name, "int field has no size" });
                continue;
            }

            for (std::string const& columnName : FlattenedColumnNames(field))
            {
                if (!seenColumns.insert(columnName).second)
                    result.errors.push_back({ table.name, field.name,
                        "flattened column name '" + columnName + "' collides with another column" });
            }
        }
    }

    if (!result.errors.empty())
        return result;

    std::ostringstream out;
    out << "// Generated by db_schema_setup_generate. Do not edit.\n";
    out << "// WoWDBDefs commit: " << wowdbdefsCommit << "\n";
    out << "#include \"Dbc/DbcTableMeta.h\"\n\n";
    out << "#include <algorithm>\n";
    out << "#include <cctype>\n";
    out << "#include <cstring>\n\n";

    for (DbdTable const& table : sorted)
    {
        std::string const& id = table.name;

        if (!table.layoutHashes.empty())
        {
            out << "static uint32_t const g_dbcLayoutHashes_" << id << "[] = {";
            bool first = true;
            for (std::string const& hash : table.layoutHashes)
            {
                out << (first ? " " : ", ") << "0x" << hash << "u";
                first = false;
            }
            out << " };\n";
        }

        out << "static DbcFieldMeta const g_dbcFields_" << id << "[] = {\n";
        for (DbdResolvedField const& field : table.fields)
            EmitFieldInitializer(out, field);
        out << "};\n\n";
    }

    out << "static DbcTableMeta const g_dbcTables[] = {\n";
    for (DbdTable const& table : sorted)
    {
        std::string fileStem = ToLower(table.name);
        out << "    { \"" << EscapeCString(table.name) << "\", \"" << fileStem << "\", \"dbc_" << fileStem << "\", "
            << (table.layoutHashes.empty() ? "nullptr" : ("g_dbcLayoutHashes_" + table.name)) << ", "
            << table.layoutHashes.size() << "u, g_dbcFields_" << table.name << ", " << table.fields.size()
            << "u },\n";
    }
    out << "};\n\n";

    out << "std::span<DbcTableMeta const> GetDbcTables()\n{\n    return g_dbcTables;\n}\n\n";

    out << "char const* GetWowDbDefsCommit()\n{\n    return \"" << EscapeCString(wowdbdefsCommit) << "\";\n}\n\n";

    out << "DbcTableMeta const* FindDbcTable(std::string_view name)\n{\n"
           "    for (DbcTableMeta const& table : g_dbcTables)\n"
           "    {\n"
           "        if (name.size() == std::strlen(table.name) &&\n"
           "            std::equal(name.begin(), name.end(), table.name, [](char a, char b)\n"
           "            { return std::tolower(static_cast<unsigned char>(a)) == std::tolower(static_cast<unsigned char>(b)); }))\n"
           "            return &table;\n"
           "    }\n"
           "    return nullptr;\n"
           "}\n";

    result.source = out.str();
    return result;
}
